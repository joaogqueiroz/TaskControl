--CREATING TABLE--

CREATE TABLE USER_TB(
	USERID UNIQUEIDENTIFIER NOT NULL,
	NAME NVARCHAR(150) NOT NULL,
	EMAIL NVARCHAR(100) NOT NULL UNIQUE,
	PASSWORD NVARCHAR(100) NOT NULL,
	REGISTRATIONDATE DATETIME NOT NULL,
	PRIMARY KEY(USERID))
GO

CREATE TABLE TASK_TB(
	TASKID UNIQUEIDENTIFIER NOT NULL,
	NAME NVARCHAR(150) NOT NULL,
	DATE DATE NOT NULL,
	HOUR TIME(7) NOT NULL,
	DESCRIPTION NVARCHAR(100) NOT NULL,
	PRIORITY NVARCHAR(15) NOT NULL,
	USERID UNIQUEIDENTIFIER NOT NULL,
	PRIMARY KEY(TASKID),
	FOREIGN KEY(USERID)
		REFERENCES USER_TB(USERID))
GO

--PASSWORD RESET LINKS: only the SHA-256 hash of each token is stored.
--Safe to run on an existing database to add the table.--

IF OBJECT_ID('PASSWORD_RESET_TB') IS NULL
CREATE TABLE PASSWORD_RESET_TB(
	TOKENHASH CHAR(64) NOT NULL,
	USERID UNIQUEIDENTIFIER NOT NULL,
	EXPIRESAT DATETIME NOT NULL,
	USEDAT DATETIME NULL,
	PRIMARY KEY(TOKENHASH),
	FOREIGN KEY(USERID)
		REFERENCES USER_TB(USERID) ON DELETE CASCADE)
GO

